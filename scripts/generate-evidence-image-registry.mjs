import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseAtlasEvidenceIndex } from "../lib/atlasEvidenceIndex.mjs";

const root = process.cwd();
const outputPath = path.join(root, "lib", "atlasEvidenceImages.generated.ts");

export function renderEvidenceImageRegistry(artifacts = parseAtlasEvidenceIndex(root)) {
  const imports = artifacts.map((artifact, index) => `import evidenceImage${String(index + 1).padStart(3, "0")} from "../${artifact.canonicalPath}";`).join("\n");
  const entries = artifacts.map((artifact, index) => `  "${artifact.canonicalPath}": evidenceImage${String(index + 1).padStart(3, "0")},`).join("\n");
  return `// Generated by scripts/generate-evidence-image-registry.mjs. Do not edit manually.\nimport type { StaticImageData } from "next/image";\n${imports}\n\nexport const atlasEvidenceImages: Readonly<Record<string, StaticImageData>> = {\n${entries}\n};\n`;
}

function main() {
  const expected = renderEvidenceImageRegistry();
  if (process.argv.includes("--check")) {
    const actual = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
    if (actual !== expected) throw new Error("Evidence image registry is stale. Run npm run evidence:generate.");
    console.log("Evidence image registry is current.");
    return;
  }
  fs.writeFileSync(outputPath, expected);
  console.log(`Generated ${path.relative(root, outputPath)}.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
